/**
 * Copy text to the clipboard. Tries the async Clipboard API first and falls back to a hidden-textarea `execCommand("copy")`, which still
 * works in contexts where the modern API is blocked (insecure origins, some embedded frames). Resolves true only if a copy
 * actually happened, so the UI never claims success it cannot back up.
 */
export async function copyText(value: string): Promise<boolean> {
  try {
    if (navigator.clipboard?.writeText) {
      await navigator.clipboard.writeText(value);
      return true;
    }
  } catch {
    /* fall through to the legacy path */
  }
  try {
    const ta = document.createElement("textarea");
    ta.value = value;
    ta.setAttribute("readonly", "");
    ta.style.position = "fixed";
    ta.style.top = "-1000px";
    ta.style.opacity = "0";
    document.body.appendChild(ta);
    ta.select();
    const ok = document.execCommand("copy");
    document.body.removeChild(ta);
    return ok;
  } catch {
    return false;
  }
}
